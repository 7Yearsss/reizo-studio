import { mkdir, mkdtemp, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { Hono } from 'hono';
import { serve } from '@hono/node-server';
import { createApp } from '../src/main/server/app';
import { openDb } from '../src/main/server/db/client';
import { createSqliteSessionStore } from '../src/main/server/storage/sqliteSessionStore';
import { createArtifactStore } from '../src/main/server/storage/artifactStore';
import { createSettingsStore } from '../src/main/server/storage/settingsStore';
import { serializeSheetContent, workbookFromCreateSheets } from '../src/shared/sheetContent';
import { documentFromHtml } from '../src/main/server/agent/documentIO';
import { documentBlocks, parseDocumentContent } from '../src/shared/documentContent';
import { splitDocumentContext } from '../src/shared/documentReferences';
import { splitHtmlContext } from '../src/shared/htmlReferences';
import { createPresentation, parsePresentation, presentationElements } from '../src/shared/presentationContent';
import { splitPresentationContext } from '../src/shared/presentationReferences';

async function main() {
  const dataRoot = process.env.REIZO_OFFICE_FIXTURE_DIR ?? await mkdtemp(path.join(os.tmpdir(), 'reizo-office-preview-'));
  if (path.dirname(path.resolve(dataRoot)).toLowerCase() !== path.resolve(os.tmpdir()).toLowerCase() || !path.basename(dataRoot).startsWith('reizo-office-preview-')) throw new Error('Fixture data must stay in its temporary directory');
  const db = openDb(path.join(dataRoot, 'preview.db'));
  const sessions = createSqliteSessionStore(db);
  const existingSession = (await sessions.list()).find((item) => item.title === 'Excel 交互验收');
  const session = existingSession ? await sessions.get(existingSession.id) : await sessions.create('Excel 交互验收');
  if (!session) throw new Error('Fixture session missing');
  const artifacts = createArtifactStore(db, dataRoot);
  const result = workbookFromCreateSheets([{ name: '预算', values: [['项目', '金额'], ['设计', 120], ['研发', 360]], formulas: [{ cell: 'B4', formula: '=SUM(B2:B3)' }] }, { name: '备注', values: [['验收备注']] }]);
  if ('error' in result) throw new Error(result.error);
  const existingWorkbook = (await artifacts.listBySession(session.id)).find((item) => item.name === '验收预算.xlsx');
  const workbook = existingWorkbook ?? await artifacts.create({ sessionId: session.id, name: '验收预算.xlsx', kind: 'sheet', content: serializeSheetContent(result.content), source: 'manual' });
  const existingDocument = (await artifacts.listBySession(session.id)).find((item) => item.name === 'Doc 审核验收');
  if (!existingDocument) await artifacts.create({ sessionId: session.id, name: 'Doc 审核验收', kind: 'doc', source: 'manual', content: JSON.stringify(documentFromHtml('<h2>发布计划</h2><p>预计周一发布。</p><p><strong>预算保持 100 元不变。</strong></p>')) });
  const existingHtml = (await artifacts.listBySession(session.id)).find((item) => item.name === 'HTML-review.html');
  if (!existingHtml) await artifacts.create({ sessionId: session.id, name: 'HTML-review.html', kind: 'html', source: 'manual', content: '<!doctype html>\n<html lang="zh-CN">\n<head>\n<meta charset="utf-8">\n<title>页面验收</title>\n<style>body{font-family:system-ui;padding:36px;background:#faf7f2;color:#292524}h1{color:#c05a2b}button{padding:10px 16px;border-radius:8px;border:1px solid #c05a2b;background:white}</style>\n</head>\n<body>\n<h1>原始标题</h1>\n<p>保留这段说明。</p>\n<button id="counter">计数：0</button>\n<script>let count=0;document.getElementById("counter").onclick=function(){this.textContent="计数："+(++count)}</script>\n</body>\n</html>' });
  const settings = createSettingsStore(dataRoot);
  const existingDeck = (await artifacts.listBySession(session.id)).find((item) => item.name === 'PPT 审核验收');
  if (!existingDeck) await artifacts.create({ sessionId: session.id, name: 'PPT 审核验收', kind: 'presentation', source: 'manual', content: JSON.stringify(createPresentation('发布计划')) });
  const app = createApp({ dataRoot, db, sessionStore: sessions, settingsStore: settings, port: 47170, devServerOrigin: 'http://127.0.0.1:47171', skillsDirs: [] });
  app.get('/_office/capture', (c) => c.html('<meta charset="utf-8"><title>Office 验收截图</title><form method="post"><label>截图名称<input name="name" required></label><label>截图数据<textarea name="image" required></textarea></label><button>保存截图</button></form>'));
  app.post('/_office/capture', async (c) => {
    const body = await c.req.parseBody();
    if (typeof body.name !== 'string' || !/^[a-z0-9-]{1,50}$/.test(body.name) || typeof body.image !== 'string' || body.image.length > 3000000) return c.text('Invalid capture', 400);
    const bytes = Buffer.from(body.image, 'base64');
    if (bytes[0] !== 0xff || bytes[1] !== 0xd8) return c.text('Expected JPEG', 400);
    const target = path.resolve('artifacts', 'office-qa', `${body.name}.jpg`);
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, bytes);
    return c.html(`<meta charset="utf-8"><p>截图已保存</p><code>${target}</code>`);
  });
  const configured = await app.request('http://127.0.0.1:47170/api/settings', { method: 'PUT', headers: { host: '127.0.0.1:47170', 'content-type': 'application/json' }, body: JSON.stringify({ activeProviderId: 'custom', provider: { id: 'custom', apiKey: 'local-test-only', model: 'office-fixture', baseUrl: 'http://127.0.0.1:47172/v1' } }) });
  if (!configured.ok) throw new Error(await configured.text());
  const mock = new Hono();
  mock.get('/v1/models', (c) => c.json({ data: [{ id: 'office-fixture' }] }));
  mock.post('/v1/chat/completions', async (c) => {
    const body = await c.req.json();
    const messages = body.messages as { role: string; content: unknown }[];
    const lastUser = messages.map((m) => m.role).lastIndexOf('user');
    const turn = messages.slice(lastUser);
    const tools = turn.filter((m) => m.role === 'tool');
    const context = String(turn[0]?.content ?? '');
    const targetId = context.match(/Workbook .*? id=([\w-]+)/)?.[1] ?? workbook.id;
    const current = await artifacts.get(targetId);
    const cell = context.match(/showing=([A-Z]+\d+):/)?.[1] ?? 'B2';
    let delta: Record<string, unknown>;
    let finish = 'stop';
    const docRef = splitDocumentContext(context).refs[0];
    const htmlRef = splitHtmlContext(context).refs[0];
    const pptRef = splitPresentationContext(context).refs[0];
    if (pptRef && tools.length < 2) {
      finish = 'tool_calls';
      const artifact = await artifacts.get(pptRef.artifactId); const deck = artifact && parsePresentation(artifact.content);
      const slide = deck && (deck.slides.find((s) => s.id === pptRef.slideId) ?? deck.slides[0]);
      const element = slide && presentationElements(slide).find((e) => pptRef.elementIds?.length ? pptRef.elementIds.includes(e.element.id ?? '') : e.element.type === 'text')?.element;
      const name = tools.length === 0 ? 'read_presentation' : 'propose_presentation_edits';
      const args = tools.length === 0 ? { artifactId: pptRef.artifactId, slideId: slide?.id } : { artifactId: pptRef.artifactId, expectedVersion: artifact?.version, operations: [{ op: 'updateElement', slideId: slide?.id, elementId: element?.id, patch: { runs: [{ text: '审核后的发布计划' }] } }] };
      delta = { role: 'assistant', tool_calls: [{ index: 0, id: `fixture-${name}-${Date.now()}`, type: 'function', function: { name, arguments: JSON.stringify(args) } }] };
    } else if (pptRef) delta = { role: 'assistant', content: 'PPT 修改建议已生成，标题尚未改动。请查看修改前后页面再接受或拒绝。' };
    else if (htmlRef && tools.length < 2) {
      finish = 'tool_calls';
      const page = await artifacts.get(htmlRef.artifactId);
      const name = tools.length === 0 ? 'read_html' : 'propose_html_edits';
      const args = tools.length === 0 ? { artifactId: htmlRef.artifactId } : { artifactId: htmlRef.artifactId, expectedVersion: page?.version, edits: [{ oldText: htmlRef.selection ? page?.content.slice(htmlRef.selection.start, htmlRef.selection.end) : '<h1>原始标题</h1>', newText: '<h1>审核后的标题</h1>' }] };
      delta = { role: 'assistant', tool_calls: [{ index: 0, id: `fixture-${name}-${Date.now()}`, type: 'function', function: { name, arguments: JSON.stringify(args) } }] };
    } else if (htmlRef) delta = { role: 'assistant', content: 'HTML 建议已生成，源码暂未修改。请查看差异与页面效果后接受或拒绝。' };
    else if (docRef && tools.length < 2) {
      finish = 'tool_calls';
      const doc = await artifacts.get(docRef.artifactId);
      const parsed = doc ? parseDocumentContent(doc.content) : null;
      const target = parsed ? documentBlocks(parsed).find((b) => b.type === 'paragraph') : null;
      const name = tools.length === 0 ? 'read_document' : 'propose_document_edits';
      const selected = docRef.selection;
      const args = tools.length === 0 ? { artifactId: docRef.artifactId } : { artifactId: docRef.artifactId, expectedVersion: doc?.version, operations: [{ op: 'replaceText', blockId: selected?.blockId ?? target?.id, start: selected?.start ?? 0, end: selected?.end ?? target?.inlineSize, text: '预计周五发布。' }] };
      delta = { role: 'assistant', tool_calls: [{ index: 0, id: `fixture-${name}-${Date.now()}`, type: 'function', function: { name, arguments: JSON.stringify(args) } }] };
    } else if (docRef) delta = { role: 'assistant', content: '修改建议已生成，原文未改动。请在 Doc 工作区接受或拒绝。' };
    else if (tools.length < 2) {
      finish = 'tool_calls';
      const name = tools.length === 0 ? 'read_sheet' : 'generate_sheet';
      const args = tools.length === 0 ? { artifactId: targetId } : { title: '验收预算', sourceArtifactId: targetId, expectedVersion: current?.version, operations: [{ op: 'setValues', sheet: 'sheet-1', start: cell, values: [[999]] }] };
      delta = { role: 'assistant', tool_calls: [{ index: 0, id: `fixture-${name}-${Date.now()}`, type: 'function', function: { name, arguments: JSON.stringify(args) } }] };
    } else delta = { role: 'assistant', content: '已将所选单元格改为 999，其他内容保持原样。' };
    const chunk = (part: Record<string, unknown>, reason: string | null) => `data: ${JSON.stringify({ id: 'office-fixture', object: 'chat.completion.chunk', created: Math.floor(Date.now() / 1000), model: 'office-fixture', choices: [{ index: 0, delta: part, finish_reason: reason }] })}\n\n`;
    return c.body(chunk(delta, null) + chunk({}, finish) + 'data: [DONE]\n\n', 200, { 'content-type': 'text/event-stream' });
  });
  const upstream = serve({ fetch: mock.fetch, hostname: '127.0.0.1', port: 47172 });
  const server = serve({ fetch: app.fetch, hostname: '127.0.0.1', port: 47170 });
  console.log(JSON.stringify({ dataRoot, sessionId: session.id, artifactId: workbook.id, api: 'http://127.0.0.1:47170' }));
  const stop = () => { server.close(); upstream.close(); app.stopCanvasJobs(); db.close(); process.exit(0); };
  process.on('SIGINT', stop); process.on('SIGTERM', stop);
}
void main();
